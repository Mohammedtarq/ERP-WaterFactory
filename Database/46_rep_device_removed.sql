/* ============================================================
   حذف جهاز من «أجهزة التطبيق»
   - جهاز بلا حركات يُحذف نهائيًا.
   - جهاز له حركات يُوقف ويُخفى من القائمة (RemovedAt) لتبقى حركاته وسجلها كما هي.
   قابل لإعادة التنفيذ بأمان.
   ============================================================ */
IF COL_LENGTH('RepDevices', 'RemovedAt') IS NULL
    ALTER TABLE RepDevices ADD RemovedAt DATETIME2 NULL;
GO
